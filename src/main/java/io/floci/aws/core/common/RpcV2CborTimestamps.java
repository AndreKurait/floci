package io.floci.aws.core.common;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import java.io.IOException;
import java.io.InputStream;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.Map;
import java.util.Set;

/**
 * The timestamp members of every JSON 1.1 service whose Smithy RPC v2 CBOR calls Floci answers with its JSON 1.1
 * handler, read once from the vendored {@code aws/rpc-v2-cbor-timestamps.json} and keyed by the service name the
 * RPC v2 path carries. Smithy RPC v2 CBOR carries a timestamp as tag 1, so {@link AwsJsonCborController} tags these
 * members of the handler's JSON 1.1 response.
 *
 * <p>The file is generated by {@code tools/aws/regen_rpcv2_cbor_timestamps.py} from botocore's service models;
 * {@code make aws-data-check} fails when it is stale against the pinned botocore. A missing or malformed resource is
 * a build defect, so loading fails with {@link IllegalStateException}.
 */
final class RpcV2CborTimestamps {

    static final String RESOURCE_NAME = "aws/rpc-v2-cbor-timestamps.json";

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private static final Map<String, Set<String>> SERVICES = VendoredResources.read(RESOURCE_NAME,
            "Smithy RPC v2 CBOR timestamp members", RpcV2CborTimestamps::parse);

    private RpcV2CborTimestamps() {
    }

    /** The timestamp members of the service the RPC v2 path names; none for a service the file does not list. */
    static Set<String> of(String serviceName) {
        return SERVICES.getOrDefault(serviceName, Set.of());
    }

    static Map<String, Set<String>> parse(InputStream in) throws IOException {
        JsonNode services = MAPPER.readTree(in).path("services");
        if (!services.isObject() || services.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no services");
        }
        Map<String, Set<String>> members = new LinkedHashMap<>();
        for (Map.Entry<String, JsonNode> service : services.properties()) {
            if (!service.getValue().isArray()) {
                throw new IllegalStateException(RESOURCE_NAME + " lists no members for " + service.getKey());
            }
            Set<String> names = new LinkedHashSet<>();
            service.getValue().forEach(name -> names.add(name.asText()));
            members.put(service.getKey(), Set.copyOf(names));
        }
        return Map.copyOf(members);
    }
}
